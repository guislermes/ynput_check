"""
node_003_packages_repo — write package.py trees under the studio packages root

Idempotent: same SoftwareSpec → same files. No Rez import required to author.
"""

from __future__ import annotations

import os
from pathlib import Path

from node_002_contracts import SoftwareSpec, snippet_demo_softwares

HERE = Path(__file__).resolve().parent
DEFAULT_REZ_ROOT = HERE / "_rez_root"


def snippet_rez_root(explicit: Path | str | None = None) -> Path:
    if explicit is not None:
        return Path(explicit).expanduser().resolve()
    env = os.environ.get("REZ_STUDIO_ROOT")
    if env:
        return Path(env).expanduser().resolve()
    return DEFAULT_REZ_ROOT.resolve()


def snippet_packages_path(rez_root: Path | None = None) -> Path:
    return (rez_root or snippet_rez_root()) / "packages"


def snippet_package_dir(spec: SoftwareSpec, rez_root: Path | None = None) -> Path:
    return snippet_packages_path(rez_root) / spec.name / spec.version


def _render_package_py(spec: SoftwareSpec) -> str:
    requires = ",\n".join(f'    "{r}"' for r in spec.requires)
    tools = ",\n".join(f'    "{t}"' for t in spec.tools)
    cmd_lines: list[str] = []
    for key, value in spec.environ:
        cmd_lines.append(f'    env.{key} = "{value}"')
    if spec.pythonpath_append_root:
        cmd_lines.append('    env.PYTHONPATH.append("{root}/python")')
    if spec.path_append_bin:
        cmd_lines.append('    env.PATH.append("{root}/bin")')
    if not cmd_lines:
        cmd_lines.append("    pass")
    commands_body = "\n".join(cmd_lines)

    return f'''\
# Auto-generated by stage_0060_rez_env — safe to re-bootstrap.

name = "{spec.name}"

version = "{spec.version}"

description = "{spec.description}"

requires = [
{requires}
]

tools = [
{tools}
]


def commands():
{commands_body}
'''


def snippet_write_software(
    spec: SoftwareSpec,
    rez_root: Path | None = None,
) -> Path:
    """Write package.py (+ empty bin/python dirs). Returns package version dir."""
    pkg_dir = snippet_package_dir(spec, rez_root)
    pkg_dir.mkdir(parents=True, exist_ok=True)
    (pkg_dir / "bin").mkdir(exist_ok=True)
    (pkg_dir / "python").mkdir(exist_ok=True)
    (pkg_dir / "package.py").write_text(_render_package_py(spec), encoding="utf-8")

    # tiny tool stub so PATH append has something visible
    if spec.tools:
        hello = pkg_dir / "bin" / f"{spec.tools[0]}.stub.txt"
        hello.write_text(
            f"stub tool for {spec.name}-{spec.version}\n",
            encoding="utf-8",
        )
    return pkg_dir


def snippet_bootstrap_packages(
    specs: list[SoftwareSpec] | None = None,
    rez_root: Path | None = None,
) -> list[Path]:
    specs = specs or snippet_demo_softwares()
    return [snippet_write_software(s, rez_root) for s in specs]


if __name__ == "__main__":
    root = snippet_rez_root()
    written = snippet_bootstrap_packages(rez_root=root)
    print(f"packages_path: {snippet_packages_path(root)}")
    for path in written:
        print("  wrote", path / "package.py")
